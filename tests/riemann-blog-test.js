'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const dir=path.join(__dirname,'../blog/ai-riemann-hypothesis');
const M=require(path.join(dir,'model.js'));
assert.deepEqual(M.sieve(20),[2,3,5,7,11,13,17,19]);
const d=M.primeData(100000);
assert.equal(d.primes.filter(p=>p<=100).length,25);
assert.ok(Math.abs(M.error(d,10000).g-1.749)<.002);
assert.ok(Math.abs(M.error(d,100000).g-3.671)<.002);
assert.deepEqual(M.exponents(.5,4.5,2),[.5,-3,.5,.5]);
assert.ok(Math.abs(Math.max(...M.exponents(1/3,4.5,2,2))-2/3)<1e-12);
assert.equal(M.toy(1e6,1000).total,2000);
assert.ok(M.toy(1e6,100).total>2000);
assert.equal(M.lattice(5).length,8);
assert.equal(M.lattice(3).length,0);
const h=fs.readFileSync(path.join(dir,'index.html'),'utf8'),j=fs.readFileSync(path.join(dir,'article.js'),'utf8');
const ids=[...h.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length);
for(const m of h.matchAll(/href="#([^"]+)"/g))assert.ok(ids.includes(m[1]),m[1]);
for(const m of j.matchAll(/\b(?:\$|put|num|svg)\('([^']+)'/g))assert.ok(ids.includes(m[1])||m[1]==='rh-term-',m[1]);
assert.ok(fs.readFileSync(path.join(__dirname,'../assets/js/data.js'),'utf8').includes('blog/ai-riemann-hypothesis/index.html'));
console.log('Riemann article model and markup checks passed');
